"""Count regional events from a frame-level detection workbook."""
from pathlib import Path
import argparse,csv,json,sys
import pandas as pd
ROOT=Path(__file__).resolve().parents[2];sys.path.insert(0,str(ROOT/'03_code/frequency'))
import postproc
REGIONS={'operculum':(1,2),'pectoral':(3,4),'caudal':(5,6,7)}

def main():
 ap=argparse.ArgumentParser(description=__doc__)
 ap.add_argument('--detections',type=Path,required=True,help='bbox_data.xlsx generated by infer_video.py')
 ap.add_argument('--total-frames',type=int,required=True,help='Number of decoded video frames')
 ap.add_argument('--output',type=Path,required=True)
 a=ap.parse_args()
 if a.total_frames<=0:ap.error('total-frames must be positive')
 dest=a.output.resolve();dest.mkdir(parents=True,exist_ok=True);wc=dest/'region_counts_10s.csv';ec=dest/'event_anchors.csv'
 if wc.exists() or ec.exists():ap.error('Output files already exist; use a new output directory')
 df=pd.read_excel(a.detections);need={'帧编号','类别','置信度'}
 if not need.issubset(df.columns):raise ValueError('Missing columns: '+', '.join(need-set(df.columns)))
 windows=[];events=[]
 for name,states in REGIONS.items():
  region=df[df['类别'].isin(states)].copy()
  anchors=postproc.detect_events(region,name) if len(region) else []
  events.extend({'region':name,'anchor_frame':int(i)} for i in anchors)
  for j in range(a.total_frames//300):
   start=j*300;count=sum(start<=i<start+300 for i in anchors)
   windows.append({'region':name,'window_index':j,'start_seconds':j*10,'end_seconds':(j+1)*10,'events':count})
 with wc.open('w',encoding='utf-8-sig',newline='') as f:
  w=csv.DictWriter(f,fieldnames=['region','window_index','start_seconds','end_seconds','events']);w.writeheader();w.writerows(windows)
 with ec.open('w',encoding='utf-8-sig',newline='') as f:
  w=csv.DictWriter(f,fieldnames=['region','anchor_frame']);w.writeheader();w.writerows(events)
 print('complete 10-second windows per region:',a.total_frames//300,'events:',len(events))
if __name__=='__main__':main()
